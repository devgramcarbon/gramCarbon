    doc.fontSize(7).font('Helvetica').text('Page (sheet)', left + titleW, y + 6, { width: pageW, align: 'center' });
    doc.fontSize(10).font('Helvetica-Bold').text('1 / 1', left + titleW, y + 20, { width: pageW, align: 'center' });
    doc.fontSize(13).font('Helvetica-Bold').text('zeroearth', left + titleW + pageW + 8, y + 6);
    doc.fontSize(7).font('Helvetica').text('ZeroEarth Private Limited', left + titleW + pageW + 8, y + 20);
    doc.text('STPI, Phase 1, Technopark, Thiruvananthapuram, Kerala', left + titleW + pageW + 8, y + 29, { width: coW - 16 });
    y += 40;

    // Delivered To | Date/GRN box
    const dtW = width * 0.65, infoW = width - dtW;
    const dtH = 60;
    doc.rect(left, y, dtW, dtH).stroke();
    doc.rect(left + dtW, y, infoW, dtH / 2).stroke();
