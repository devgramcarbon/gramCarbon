export async function generateDummyDoc(
  order: Pick<IPurchaseOrder, 'poNumber' | 'client' | 'batch' | 'qty'>,
  docType: DummyDocType
): Promise<{ key: string; url: string }> {
  const buffer =
    docType === 'EWAY_BILL' ? await renderEwayBillPdf(order) :
    docType === 'DN' ? await renderGrnPdf(order) :
    docType === 'INVOICE' ? await renderInvoicePdf(order) :
    await renderDummyPdf(order, docType);
  return uploadToS3(buffer, 'application/pdf', 'po-documents');
}
