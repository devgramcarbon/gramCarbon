    doc.font('Helvetica-Bold').text('PROJECT REF', left + 5, y + 4, { continued: true });
    doc.font('Helvetica').text(`  ${PLACEHOLDER}`);
    y += 16;

    // Goods table
    const headers = ['NO', 'QUANTITY KG', 'DESCRIPTION', 'ITEM CODE', 'REMARKS/COMMENTS'];
    const colW = [30, 70, width - 30 - 70 - 90 - 120, 90, 120];
    let x = left;
    doc.fontSize(7).font('Helvetica-Bold');
