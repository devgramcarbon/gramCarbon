    doc.font('Helvetica').text(PLACEHOLDER, left + dtW + 5, y + dtH - 12);
    y += dtH;

    // Our PO Ref | GRN No row
    doc.rect(left, y, dtW, 16).stroke();
    doc.rect(left + dtW, y, infoW, 16).stroke();
    doc.fontSize(8).font('Helvetica').text(`OUR PO REF: ${order.poNumber}`, left + 5, y + 4);
    doc.text(`GRN NO: ${PLACEHOLDER}`, left + dtW + 5, y + 4);
